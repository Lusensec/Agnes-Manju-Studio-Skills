#!/usr/bin/env python3
"""Generate storyboard images using multi-reference I2I.

Reference strategy:
  - Character three-view (strongest identity anchor)
  - Current scene background (angle matching: wide/mid/close)
  - Related props for this scene (if defined in script)
  Max 5 refs total (Agnes limit).

Asset consistency (borrowed from ComfyUI 5-channel asset injection):
  scenes may reference top-level script asset channels via
  "location" (name in locations[]) and "props" (names in props[]) —
  their descriptions are injected into the prompt so the model does
  not invent inconsistent sets/props.

Shotlist mode (总导演): with --shotlist, work per SHOT from
scripts/<project>-shotlist.json (generated by gen-shotlist.py):
  images are named scene-<shot>.png and URL keys are scene-<shot>,
  so gen-video.py --shotlist and merge-videos.py keep working.

Batch status (breakpoint resume): each run writes
scripts/<project>-storyboard-status.json with per-slot status
{success, error(+reason), pending}. Rerun with --retry-failed to
only redo failed slots.

Usage:
    python gen-storyboard.py "项目名" [--scene N] [--size 1K|2K]
    python gen-storyboard.py "项目名" --shotlist
    python gen-storyboard.py "项目名" --retry-failed
"""
import json
import sys
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from load_env import API_KEY, PROJECT_ROOT
from track import track_file

BASE_IMG = "https://api.agnes-ai.cn/v1/images/generations"
STYLE_PREFIX = {
    "动画": "anime style, clean lines, vibrant colors, ",
    "写实": "photorealistic, high detail, cinematic lighting, ",
    "水墨": "Chinese ink wash painting, minimalist, elegant, ",
    "赛博朋克": "cyberpunk, neon lights, futuristic, dark tones, ",
    "二次元": "2D anime, cute, pastel colors, soft shading, ",
}
SLEEP_BY_SIZE = {"1K": 3, "2K": 7, "3K": 60, "4K": 60}


def gen_image(prompt: str, size="1K", ratio="16:9", ref_urls: list = None) -> str:
    body = {
        "model": "agnes-image-2.5-flash",
        "prompt": prompt,
        "size": size,
        "ratio": ratio,
        "extra_body": {"response_format": "url"}
    }
    if ref_urls:
        body["extra_body"]["image"] = ref_urls[:5]  # Max 5
    data = json.dumps(body).encode()
    req = urllib.request.Request(
        BASE_IMG, data=data,
        headers={"Authorization": f"Bearer {API_KEY}", "Content-Type": "application/json"},
        method="POST"
    )
    resp = urllib.request.urlopen(req, timeout=360).read()
    return json.loads(resp)["data"][0]["url"]


def load_urls(project: str) -> dict:
    """Load all stored image URLs."""
    f = PROJECT_ROOT / project / "scripts" / f"{project}-image-urls.json"
    if f.exists():
        return json.loads(f.read_text(encoding="utf-8"))
    return {}


def asset_context(script: dict, scene: dict) -> str:
    """Inject scene-referenced asset channel descriptions (location/props)."""
    parts = []
    loc = scene.get("location")
    if loc:
        for a in script.get("locations", []):
            if a.get("name") == loc:
                parts.append(f"location: {loc} ({a.get('description', '')})")
                break
    for pname in (scene.get("props") or [])[:3]:
        for a in script.get("props", []):
            if a.get("name") == pname:
                parts.append(f"prop: {pname} ({a.get('description', '')})")
                break
    return " | ".join(parts)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)

    project = sys.argv[1]
    scene_filter = None
    image_size = None
    use_shotlist = False
    retry_failed = False
    if "--scene" in sys.argv:
        scene_filter = int(sys.argv[sys.argv.index("--scene") + 1])
    if "--size" in sys.argv:
        image_size = sys.argv[sys.argv.index("--size") + 1]
    if "--shotlist" in sys.argv:
        use_shotlist = True
    if "--retry-failed" in sys.argv:
        retry_failed = True

    sleep_sec = SLEEP_BY_SIZE.get(image_size or "1K", 3)

    proj_dir = PROJECT_ROOT / project
    img_dir = proj_dir / "images"
    img_dir.mkdir(parents=True, exist_ok=True)
    script_dir = proj_dir / "scripts"

    scripts = list(script_dir.glob(f"{project}-script.json"))
    if not scripts:
        print("[ERROR] 未找到剧本", file=sys.stderr)
        sys.exit(1)
    script = json.loads(scripts[0].read_text(encoding="utf-8"))
    config = script.get("config", {})
    style = config.get("style", "动画")
    style_prefix = STYLE_PREFIX.get(style, "")
    if image_size is None:
        image_size = config.get("image_size", "1K")
        sleep_sec = SLEEP_BY_SIZE.get(image_size, 3)
    aspect_ratio = config.get("aspect_ratio", "16:9")

    # Load all available URLs (character three-views, backgrounds, props)
    urls = load_urls(project)
    char_refs = [v for k, v in urls.items() if "three-view" in k]

    # ---- build work items (scenes or shots) ----
    shotlist = None
    if use_shotlist:
        sl_file = script_dir / f"{project}-shotlist.json"
        if not sl_file.exists():
            print(f"[ERROR] 未找到 shotlist: {sl_file}", file=sys.stderr)
            print(f"       先运行 → python script-writer/examples/gen-shotlist.py \"{project}\"")
            sys.exit(1)
        shotlist = json.loads(sl_file.read_text(encoding="utf-8"))
        shots = shotlist.get("shots", [])
        if scene_filter:
            shots = [s for s in shots if s.get("shot") == scene_filter]
        items = []
        for s in shots:
            sid = s.get("shot", 0)
            desc = s.get("frame", "")
            desc_zh = f"{s.get('title', '')} | 运镜: {s.get('camera', '')}"
            items.append({"sid": sid, "desc_en": desc, "desc_zh": desc_zh,
                         "scene_ref": s.get("scene_id")})
        mode = "shotlist"
    else:
        scenes = script.get("scenes", [])
        if scene_filter:
            scenes = [s for s in scenes if s.get("scene_id") == scene_filter]
        items = [{"sid": s.get("scene_id", 0),
                  "desc_en": s.get("description", ""),
                  "desc_zh": s.get("description_zh", s.get("description", "")),
                  "scene_ref": None, "raw": s} for s in scenes]
        mode = "scene"

    if not items:
        print("[ERROR] 没有可生成的分镜", file=sys.stderr)
        sys.exit(1)

    # ---- breakpoint resume: --retry-failed only redoes failed slots ----
    status_file = script_dir / f"{project}-storyboard-status.json"
    slots = {}
    if retry_failed and status_file.exists():
        prev = json.loads(status_file.read_text(encoding="utf-8")).get("slots", {})
        bad = {k for k, v in prev.items() if v.get("status") != "success"}
        kept = [it for it in items if str(it["sid"]) in bad or not (img_dir / f"scene-{it['sid']}.png").exists()]
        if not kept:
            print("✅ status 中无失败槽（或文件均已生成），无需重跑。")
            sys.exit(0)
        items = kept
        print(f"🔁 --retry-failed: 仅重做 {len(kept)} 个失败/缺失槽")
    for it in items:
        slots[str(it["sid"])] = {"status": "pending"}

    print(f"📷 生成 {len(items)} 张分镜图 ({mode} 模式)...")
    print(f"   参考策略: 角色三视图({len(char_refs)}张) + 场景背景 + 相关道具 + 资产上下文")
    print(f"   每场景最多 5 张参考\n")

    url_map = {}
    stopped_round = False
    for i, it in enumerate(items):
        sid = it["sid"]
        desc_en = it["desc_en"]
        scene_raw = it.get("raw") or {}

        # Build reference set for this slot
        refs = []
        refs.extend(char_refs[:2])  # Max 2 character refs
        bg_sid = it.get("scene_ref") if it.get("scene_ref") is not None else sid
        if bg_sid is not None:
            bg_key = f"bg-{bg_sid}-mid"
            if bg_key in urls:
                refs.append(urls[bg_key])
        for pname in (scene_raw.get("props") or [])[:2]:
            prop_key = f"prop-{pname}-front"
            if prop_key in urls:
                refs.append(urls[prop_key])
        refs = refs[:5]  # Hard limit

        ref_desc = ""
        if refs:
            ref_desc = f" [Reference images: {', '.join([r.split('/')[-1][:20] for r in refs])}]"
        ctx = asset_context(script, scene_raw) if mode == "scene" else ""
        prompt = f"{style_prefix}{desc_en}. Maintain character consistency with reference images.{ref_desc}"
        if ctx:
            prompt += f" [Asset context: {ctx}]"
        if shotlist:
            notes = str(shotlist.get("director_notes", ""))[:120]
            if notes:
                prompt += f" Continuity: {notes}"

        print(f"  [{i+1}/{len(items)}] slot-{sid}: {str(it.get('desc_zh',''))[:30]}... ({len(refs)} refs)")
        out_file = img_dir / f"scene-{sid}.png"
        try:
            img_url = gen_image(prompt, size=image_size, ratio=aspect_ratio, ref_urls=refs)
            out_file.write_bytes(urllib.request.urlopen(img_url).read())
            url_map[f"scene-{sid}"] = img_url
            slots[str(sid)] = {"status": "success", "file": out_file.name}
            track_file(project, "image", str(out_file), f"分镜 {sid}",
                       f"style={style},refs={len(refs)},mode={mode}")
            print(f"     ✅ {out_file.name}")
        except urllib.error.HTTPError as e:
            if e.code in (429, 503):
                reason = f"HTTP {e.code}: 限流/队列满（重试后仍失败），本轮停止"
                slots[str(sid)] = {"status": "error", "reason": reason}
                print(f"     ❌ {reason}")
                stopped_round = True
                break
            body = ""
            try:
                body = e.read().decode("utf-8", "replace")[:300]
            except Exception:
                pass
            reason = f"HTTP {e.code}: {body or e.reason}"
            slots[str(sid)] = {"status": "error", "reason": reason}
            print(f"     ❌ {reason}（记录后继续下一槽）")
        except Exception as e:
            slots[str(sid)] = {"status": "error", "reason": str(e)[:300]}
            print(f"     ❌ 失败: {e}（记录后继续下一槽）")

        if not stopped_round and i < len(items) - 1:
            time.sleep(sleep_sec)

    # ---- save scene URLs (successful only) ----
    if url_map:
        save_file = script_dir / f"{project}-image-urls.json"
        existing = json.loads(save_file.read_text(encoding="utf-8")) if save_file.exists() else {}
        existing.update(url_map)
        save_file.write_text(json.dumps(existing, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"\n📝 分镜 URL 已保存")

    # ---- write batch status (breakpoint ledger) ----
    status = {
        "project": project,
        "artifact": "scene-{sid}.png",
        "mode": mode,
        "updated_at": datetime.now(timezone.utc).isoformat(),
        "slots": slots,
    }
    status_file.write_text(json.dumps(status, ensure_ascii=False, indent=2), encoding="utf-8")

    n_ok = sum(1 for v in slots.values() if v["status"] == "success")
    n_err = sum(1 for v in slots.values() if v["status"] == "error")
    print(f"\n✅ 分镜图完成: {n_ok} 成功 / {n_err} 失败（status: {status_file.name}）")

    if n_err or stopped_round:
        print("⚠️  有失败槽。稍后重新运行并加 --retry-failed 即可只补失败项：")
        print(f"   python gen-storyboard.py \"{project}\" --retry-failed")
        sys.exit(3)

    print("\n下一步：")
    print(f"  [1] 总览确认 → python storyboard-gen/examples/gen-mosaic.py \"{project}\"")
    print(f"  [2] 生成视频 → python video-composer/examples/gen-video.py \"{project}\""
          f"{' --shotlist' if use_shotlist else ''}")
    print(f"  [3] 重新生成某槽 → python gen-storyboard.py \"{project}\" --scene N")


if __name__ == "__main__":
    main()
